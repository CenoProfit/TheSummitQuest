#!/usr/bin/env python3
"""Render the full colour sprites (pets_full.py, items_full.py) and splice
them into proto/trek.html as FULLRGB, keyed by the piece's stable id.

Each frame is stored the way the hand drawn bosses are: a palette and a
run length encoded index stream, base64'd. The page draws a piece from
FULLRGB when it has an entry and falls back to the letter sprites when
it does not.

    python3 proto/art/fullpack.py
"""
import base64, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.dirname(os.path.dirname(HERE))
HTML = os.path.join(ROOT, 'proto', 'trek.html')
BEGIN = '/* FULLRGB:BEGIN generated by proto/art/fullpack.py */'
END = '/* FULLRGB:END */'

from forge import render
import numpy as np
import pets_full, items_full, gear_full


def gid(cat, name):
    return cat[0] + re.sub(r'[^a-z0-9]', '', name.lower())


def encode(rgb, alpha):
    n = rgb.shape[0]
    pal = {(0, 0, 0, 0): 0}; order = [(0, 0, 0, 0)]; idx = []
    for y in range(n):
        for x in range(n):
            key = (0, 0, 0, 0) if alpha[y, x] < 8 else (int(rgb[y, x, 0]), int(rgb[y, x, 1]), int(rgb[y, x, 2]), 255)
            if key not in pal:
                pal[key] = len(order); order.append(key)
            idx.append(pal[key])
    assert len(order) <= 256, len(order)
    out = bytearray(); i = 0
    while i < len(idx):
        v = idx[i]; k = 1
        while i + k < len(idx) and idx[i + k] == v and k < 255:
            k += 1
        out += bytes((k, v)); i += k
    cols = ','.join('0' if c[3] == 0 else '0x%02x%02x%02x' % c[:3] for c in order)
    return '{n:%d,p:[%s],d:"%s"}' % (n, cols, base64.b64encode(bytes(out)).decode()), len(order)


def main():
    rows = []; ncol = []
    for name, fn in pets_full.BUILD:
        fr = []
        for f in (0, 1):
            e, k = encode(*render(fn(f))); fr.append(e); ncol.append(k)
        rows.append(' %s:{f:[%s]}' % (gid('pet', name), ','.join(fr)))
    for name, fn, frames, grip in items_full.BUILD:
        e, k = encode(*render(fn(0))); ncol.append(k)
        g = ',grip:[0,%d,95,%d]' % grip if grip else ''
        rows.append(' %s:{f:[%s]%s}' % (gid('staff', name), e, g))
    done = {gid('staff', n) for n, *_ in items_full.BUILD}
    for g in gear_full.GEAR:
        if g[1] == 'pet' or gear_full.gid(g) in done:
            continue
        C = gear_full.piece(g)
        if C is None:
            continue
        e, k = encode(*render(C)); ncol.append(k)
        gp = ''
        if g[1] in ('sword', 'staff'):
            m = C.mats.index(C.kit.grip) if C.kit.grip in C.mats else -1
            ys, xs = np.nonzero(C.mat == m)
            if len(xs):
                gp = ',grip:[%d,%d,%d,%d]' % (xs.min(), ys.min(), xs.max(), ys.max())
        rows.append(' %s:{f:[%s]%s}' % (gear_full.gid(g), e, gp))
    block = BEGIN + '\nconst FULLRGB={\n' + ',\n'.join(rows) + '\n};\n' + END
    s = open(HTML).read()
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, s, flags=re.S)
    else:
        a = s.index('const ART=new Map(), ARTMAX=')
        s = s[:a] + block + '\n' + s[a:]
    open(HTML, 'w').write(s)
    print('fullpack: %d sprites, %d to %d colours each, %d KB' % (
        len(ncol), min(ncol), max(ncol), len(block) // 1024))


if __name__ == '__main__':
    main()
