#!/usr/bin/env python3
"""Build the bright theme for index.html from its dark stylesheet.

The game was drawn dark, with about 280 colours written straight into
the CSS. Hand-copying every one into a light version would go stale the
first time a rule changed, so this reads the main <style> block and
writes, for every rule that sets a colour, the same rule scoped under
html[data-theme=light] with each colour flipped:

  * lightness is inverted, so navy panels become paper and pale ink
    becomes dark ink, while gold and green go a few shades deeper
    instead of washing out;
  * the cool blue greys of the dark UI come out as warm off white;
  * drop shadows stay dark but soft, rather than turning white.

Every colour property of a rule is copied, var() ones included, so the
overrides cascade among themselves in the same order the originals did.
The other background longhands come along too: a copied `background`
shorthand resets them, and a later rule that set only background-repeat
would otherwise lose to it.

Inline colours inside style="..." attributes are matched with attribute
selectors, which beat inline styles when marked !important.

Output goes between the LIGHT-THEME markers in index.html. Re-run it
after changing the dark CSS:  python3 tools/lighttheme.py
"""
import colorsys, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'index.html'
BEGIN = '/* LIGHT-THEME:BEGIN generated by tools/lighttheme.py, do not edit by hand */'
END = '/* LIGHT-THEME:END */'
P = 'html[data-theme=light]'

COLOR_PROPS = re.compile(r'^(color|background(-color|-image|-repeat|-size|-position|-clip|-origin|-attachment)?|border(-top|-right|-bottom|-left)?(-color)?|'
                         r'outline(-color)?|box-shadow|text-shadow|fill|stroke|caret-color|'
                         r'text-decoration-color|column-rule-color|accent-color|filter)$')
LIT = re.compile(r'#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)')


def parse(c):
    if c.startswith('#'):
        h = c[1:]
        if len(h) in (3, 4):
            h = ''.join(x * 2 for x in h)
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r, g, b, a
    nums = [x.strip() for x in c[c.index('(') + 1:-1].replace('/', ',').split(',')]
    r, g, b = (float(x[:-1]) * 2.55 if x.endswith('%') else float(x) for x in nums[:3])
    a = float(nums[3]) if len(nums) > 3 else 1.0
    return r, g, b, a


def fmt(r, g, b, a):
    r, g, b = (max(0, min(255, round(x))) for x in (r, g, b))
    if a >= 0.999:
        return '#%02x%02x%02x' % (r, g, b)
    return 'rgba(%d,%d,%d,%s)' % (r, g, b, ('%.3f' % a).rstrip('0').rstrip('.'))


def flip(c, shadow=False):
    r, g, b, a = parse(c)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if shadow and l < 0.35:
        # a drop shadow keeps falling the same way, just softer and warm
        return fmt(60, 48, 28, a * 0.35)
    l2 = 1 - l
    if l2 > 0.55 and (s < 0.6 or l2 > 0.85):
        # the cool slate of the dark UI turns into warm paper
        h, s = 40 / 360, min(s, 0.35) * 0.9
    elif l2 < 0.5 and s < 0.25:
        h = 220 / 360
    if l2 < 0.5 and s >= 0.6:
        # bright accents: deep enough to read on paper, not muddy
        l2 = max(0.26, min(l2, 0.42))
    if shadow:
        a *= 0.6
    r2, g2, b2 = colorsys.hls_to_rgb(h, l2, s)
    return fmt(r2 * 255, g2 * 255, b2 * 255, a)


def flip_value(prop, v):
    shadow = prop in ('box-shadow', 'filter')
    if prop == 'filter' and 'drop-shadow' not in v:
        return None
    return LIT.sub(lambda m: flip(m.group(0), shadow), v)


def split_top(s, sep):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return out


def blocks(css):
    """yield (prelude, body) for each top level block"""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            return
        pre = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{':
                depth += 1
            elif css[k] == '}':
                depth -= 1
            k += 1
        yield pre, css[j + 1:k - 1]
        i = k


def strip_comments(css):
    return re.sub(r'/\*.*?\*/', '', css, flags=re.S)


def scope(sel):
    sel = sel.strip()
    if not sel or sel == ':root':
        return None
    if sel.startswith('html'):
        return P + sel[4:]
    return P + ' ' + sel


def rules(css):
    out = []
    for pre, body in blocks(css):
        while pre.startswith('}'):
            pre = pre[1:].strip()
        if pre.startswith('@font-face') or pre.startswith('@keyframes'):
            continue
        if pre.startswith('@media') or pre.startswith('@supports'):
            inner = rules(body)
            if inner:
                out.append(pre + '{\n' + '\n'.join(inner) + '\n}')
            continue
        sels = [scope(s) for s in split_top(pre, ',')]
        sels = [s for s in sels if s]
        if not sels:
            continue
        decls = []
        for d in split_top(body, ';'):
            if ':' not in d:
                continue
            prop, val = d.split(':', 1)
            prop = prop.strip().lower()
            val = val.strip()
            if not COLOR_PROPS.match(prop):
                continue
            nv = flip_value(prop, val)
            if nv is None:
                continue
            decls.append(prop + ':' + nv)
        if decls and any(LIT.search(x) or 'var(' in x for x in decls):
            out.append(','.join(sels) + '{' + ';'.join(decls) + '}')
    return out


def inline_rules(html):
    seen, out = set(), []
    for m in re.finditer(r'style="([^"]*)"', html):
        for d in m.group(1).split(';'):
            if ':' not in d:
                continue
            prop, val = (x.strip() for x in d.split(':', 1))
            if prop != 'color' or not LIT.fullmatch(val):
                continue
            key = 'color:' + val
            if key in seen:
                continue
            seen.add(key)
            out.append('%s [style*="%s"]{color:%s !important}' % (P, key, flip(val)))
    return out


def main():
    html = SRC.read_text()
    m = re.search(r'<style>(.*?)</style>', html, re.S)
    css = strip_comments(m.group(1))
    gen = rules(css) + inline_rules(html)
    block = BEGIN + '\n' + '\n'.join(gen) + '\n' + END
    if BEGIN not in html:
        sys.exit('lighttheme: markers missing from index.html')
    html = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, html, flags=re.S)
    SRC.write_text(html)
    print('lighttheme: wrote %d rules into index.html' % len(gen))


if __name__ == '__main__':
    main()
